#!/usr/bin/env bash
# Демонстрация для дня 8: тот же класс переполнения, что ловит guard
# week-02, но напрямую в модель, без него — локальная llama3 через Ollama
# на M1 Pro (без ключей, без rate limit). В отличие от week-02, здесь
# модель НЕ сообщает об ошибке — она молча теряет часть промпта и отвечает
# неверно.
#
# Как это устроено (проверено эмпирически на Ollama 0.33.3):
# - OpenAI-совместимый /v1/chat/completions полностью игнорирует
#   options.num_ctx — модель всегда работает с тем контекстом, с которым
#   уже загружена. Поэтому здесь используется нативный /api/chat, который
#   при смене num_ctx реально перезагружает модель с этим размером.
# - Если промпт больше активного окна, Ollama не возвращает ошибку — она
#   молча обрезает промпт примерно до num_ctx/2 токенов и оставляет
#   короткий "keep"-хвост в начале (num_keep, по умолчанию 24 токена).
#   Поэтому секретный факт нужно ставить НЕ в самое начало (иначе он
#   попадёт в защищённый keep-хвост и выживет), а сразу после него — тогда
#   при достаточном объёме текста после факта он окажется в отброшенной
#   части.
#
#   export GROQ_API_KEY=...   # не используется здесь, но лежит рядом с
#                              # day-08-demo.sh, который тоже требует его
#   ./week-02/video/local-overflow-probe.sh

set -uo pipefail

NUM_CTX=2048
BEFORE=8   # реплик filler до факта — выводит факт за пределы num_keep
AFTER=300  # реплик filler после факта — гарантирует, что факт попадёт
           # в отброшенную (не «keep», не «tail») часть промпта

PROMPT=$(python3 -c "
unit = 'Программирование как дисциплина развивалось десятилетиями, проходя путь от перфокарт и ассемблера до современных языков высокого уровня с автоматическим управлением памятью. '
fact = 'Секретный код доступа к серверу: 4817-ZEBRA. '
text = unit * $BEFORE + fact + unit * $AFTER
text += chr(10) + chr(10) + 'Найди в тексте выше секретный код доступа и назови только его, без пояснений.'
print(text)
")

BODY=$(jq -n --arg model "llama3" --arg content "$PROMPT" --argjson num_ctx "$NUM_CTX" \
    '{model: $model, messages: [{role: "user", content: $content}], stream: false, options: {num_ctx: $num_ctx}}')

curl -sS http://localhost:11434/api/chat -H 'Content-Type: application/json' -d "$BODY" \
    | jq --argjson num_ctx "$NUM_CTX" '{num_ctx: $num_ctx, prompt_tokens_actually_used: .prompt_eval_count, answer: .message.content}'
